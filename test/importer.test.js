import { describe, expect, it } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { importJava } from '../src/importer.js';
import { generateScene } from '../src/codegen.js';
import { compileStoryboard, newDocument } from '../src/doc.js';

const strip = (actions) => actions.map(({ id, section, ...rest }) => rest);

describe('Java storyboard import', () => {
  it('reads the documented subset from Create’s own shaft scene and flags its loop as custom logic', () => {
    const src = fs.readFileSync(path.join(__dirname, 'fixtures', 'KineticsScenes.java'), 'utf8');
    const { methods } = importJava(src, 'KineticsScenes.java');
    const shaft = methods.find((m) => m.name === 'shaftAsRelay');
    expect(shaft).toMatchObject({ sceneId: 'shaft', title: 'Relaying rotational force using Shafts', basePlate: { x: 0, z: 0, size: 5 } });
    expect(shaft.actions.slice(0, 4).map((a) => [a.at, a.type])).toEqual([[0, 'show'], [0, 'show'], [0, 'kinetic'], [5, 'show']]);
    expect(shaft.unsupported.map((u) => u.reason)).toContain('control flow');
    expect(shaft.unsupported.find((u) => u.reason === 'control flow').text).toMatch(/^for \(int i = 4/);
    expect(shaft.actions.some((a) => a.type === 'text' && a.text === 'Shafts will relay rotation in a straight line.' && a.anchor.kind === 'point')).toBe(true);
    expect(methods.length).toBeGreaterThan(5);
  });

  it('imports code generated by Ponder Studio back into the same timeline', () => {
    const d = newDocument({ namespace: 'gemtools', sceneId: 'cogwheel_intro', title: 'Cogs', component: 'create:cogwheel', structureFile: 'src/main/resources/assets/gemtools/ponder/cogwheel_intro.nbt' });
    d.selections = [
      { id: 'shaft', name: 'Shaft', boxes: [[2, 1, 0, 2, 1, 1]] },
      { id: 'cog', name: 'Cogwheel', boxes: [[2, 1, 2, 2, 1, 2]] }
    ];
    d.actions = [
      { id: 'a1', type: 'show', at: 5, selection: 'shaft', direction: 'down' },
      { id: 'a2', type: 'show', at: 15, selection: 'cog', direction: 'west' },
      { id: 'a3', type: 'text', at: 20, text: 'Quote " and é', duration: 60, anchor: { kind: 'face', pos: [2, 1, 2], face: 'up' }, placeNearTarget: true, keyframe: true, color: 'green' },
      { id: 'a4', type: 'kinetic', at: 20, selection: 'shaft', speed: 32 },
      { id: 'a5', type: 'kinetic', at: 20, selection: 'cog', speed: -32.5 },
      { id: 'a6', type: 'outline', at: 25, selection: 'cog', color: 'red', duration: 30 },
      { id: 'a7', type: 'input', at: 30, anchor: { kind: 'block', pos: [2, 1, 2] }, pointing: 'down', click: 'right', item: null, sneaking: true, ctrl: false, duration: 40 },
      { id: 'a8', type: 'rotate_camera', at: 40, degrees: 90 },
      { id: 'a9', type: 'move', at: 45, selection: 'cog', offset: [0, 1, 0], duration: 20 },
      { id: 'a10', type: 'hide', at: 80, selection: 'shaft', direction: 'up' }
    ];
    const java = generateScene(d, 'com.example.gemtools.ponder').content;
    const [m] = importJava(java, 'CogwheelIntroScene.java').methods;
    expect(m.unsupported).toEqual([]);
    expect(m.sceneId).toBe('cogwheel_intro');
    expect(m.end).toBe(compileStoryboard(d).end);
    const original = compileStoryboard(d).actions;
    const imported = compileStoryboard({ ...d, selections: m.selections, actions: m.actions }).actions;
    const normalize = (list) => strip(list).map((a) => ({ ...a, text: a.text, selection: a.selection }));
    expect(normalize(imported)).toEqual(normalize(original));
  });
});
